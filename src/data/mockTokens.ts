export function generateNewCandidateToken(chain?: Chain): MemeToken {
  const chosenChain = chain || (['solana', 'bnb', 'robinhood'][Math.floor(Math.random() * 3)] as Chain);
  const candidatesForChain = POOL_NAMES.filter(p => p.chain === chosenChain);
  const picked = candidatesForChain[Math.floor(Math.random() * candidatesForChain.length)] || {
    name: `${chosenChain.toUpperCase()} Alpha Meme`,
    symbol: `$${chosenChain.slice(0, 3).toUpperCase()}ALPHA`,
    chain: chosenChain,
  };

  const isSafe = Math.random() > 0.35; // 65% chance of passing or being high quality
  const basePrice = Number((Math.random() * 0.005 + 0.0001).toFixed(6));
  const mcap = Math.floor(Math.random() * 800000 + 80000);
  const liquidityUsd = Math.floor(mcap * (Math.random() * 0.2 + 0.1));

  if (isSafe) {
    return {
      id: `${chosenChain}-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 6)}`,
      name: picked.name,
      symbol: picked.symbol,
      chain: chosenChain,
      contractAddress: `${Math.random().toString(36).slice(2, 8)}...${chosenChain.slice(0, 3)}`,
      price: basePrice,
      currentPrice: basePrice,
      athPrice: basePrice,
      change24h: Number((Math.random() * 80 + 15).toFixed(1)),
      mcap,
      liquidityUsd,
      lpLockedPercent: Number((Math.random() * 5 + 95).toFixed(1)),
      top10HolderPercent: Number((Math.random() * 7 + 5).toFixed(1)),
      devHoldingsPercent: Number((Math.random() * 1.5).toFixed(1)),
      smartMoneyScore: Math.floor(Math.random() * 15 + 85),
      rugRiskScore: Math.floor(Math.random() * 12 + 2),
      viralityScore: Math.floor(Math.random() * 20 + 80),
      mintRenounced: true,
      freezeDisabled: true,
      scrutinyStatus: 'PASSED_RAWSIGHT',
      auditBadges: ['Mint Renounced', 'LP Burned >95%', 'Dev Holdings < 2%', 'Rawsight Alpha Pass'],
      chartHistory: [basePrice * 0.85, basePrice * 0.92, basePrice],
      discoveredAt: Date.now(),
    };
  } else {
    const isInsider = Math.random() > 0.5;
    return {
      id: `${chosenChain}-reject-${Date.now().toString(36)}`,
      name: `${picked.name} [SUS]`,
      symbol: picked.symbol,
      chain: chosenChain,
      contractAddress: `${Math.random().toString(36).slice(2, 8)}...bad`,
      price: basePrice,
      currentPrice: basePrice,
      athPrice: basePrice * 1.2,
      change24h: -18.5,
      mcap: Math.floor(mcap * 0.4),
      liquidityUsd: Math.floor(Math.random() * 9000 + 1500),
      lpLockedPercent: Math.floor(Math.random() * 40 + 10),
      top10HolderPercent: Math.floor(Math.random() * 35 + 40),
      devHoldingsPercent: Math.floor(Math.random() * 20 + 12),
      smartMoneyScore: Math.floor(Math.random() * 25 + 5),
      rugRiskScore: Math.floor(Math.random() * 25 + 75),
      viralityScore: Math.floor(Math.random() * 30 + 10),
      mintRenounced: false,
      freezeDisabled: false,
      scrutinyStatus: isInsider ? 'REJECTED_INSIDER_CLUSTER' : 'REJECTED_LOW_LP',
      auditBadges: isInsider ? ['ALERT: Insider dev bundle 15%+', 'Concentrated Top 10 >40%'] : ['ALERT: LP < $10k', 'Unlocked LP 70%'],
      auditFailureReason: isInsider 
        ? 'Rawsight Scrutiny Filter: Insider wallet cluster dumping risk detected.' 
        : 'Rawsight Scrutiny Filter: Low liquidity pool depth and unlocked LP risk.',
      chartHistory: [basePrice * 1.2, basePrice],
      discoveredAt: Date.now(),
    };
  }
}
